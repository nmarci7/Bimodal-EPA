"""Translate one cone into a TLA+ module whose behaviours are the runs of the alethic layer.

A run is a use case, a switch vector (for every row of the cone that is open, whether it is switched
on for the whole run) and a firing order. The use case and the switch vector are part of the initial
state, so one TLC run explores all of them at once.

Two translators live here; `schedule` picks one.

fifo, the default. The state is a FIFO queue of tokens per input port, plus monitors. A component is
ready when one of its queues is non-empty or it has a switched-on internal fault not yet applied. One
step fires one ready component, and TLC branches on which: the firing takes the head of every non-empty
queue, applies the component's table to those heads and sends one token per output port written. A
component remembers nothing. The stopping rule ends every run: an edge never delivers a token value it
has already carried in this run. A run ends when nothing is ready (`done`). The monitor `lab` holds, per
edge, the field-wise worst token delivered; `fired` the rows that applied; `seen` the delivered values.

rounds, the older translator, kept for the differential test. Every component recomputes what it sends
from what it receives and the result is merged into monotone edge labels until a fixpoint (`done`), with
phases for guards that may drop a message.

Candidates are not in the module: a candidate *admits* a run when its never rows are not in the
switch vector and its always rows are, so the epistemic layer reads every candidate's runs off the
same explored states.

The text is deterministic: the same model, cone and options give the same file, which is what the
run cache keys on.
"""
from __future__ import annotations

import os
import re

_ID = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def q(s):
    return '"' + s + '"'


def _set(xs):
    return "{" + ", ".join(q(x) for x in xs) + "}"


def _ident(s):
    return re.sub(r"[^A-Za-z0-9_]", "_", s)


def _vector_pred(name, pin_sets, vec_rows):
    """A predicate over switch vectors F: F agrees with at least one of the pin sets.
    A pin set maps rows to 'N' (must not fire) or 'A' (must fire)."""
    if not pin_sets:
        return f"{name}(F) == FALSE"
    alts = []
    for pins in pin_sets:
        a = sorted(r for r, x in pins.items() if x == "A" and r in vec_rows)
        n = sorted(r for r, x in pins.items() if x == "N" and r in vec_rows)
        conj = []
        if a:
            conj.append(f"{_set(a)} \\subseteq F")
        if n:
            conj.append(f"F \\cap {_set(n)} = {{}}")
        alts.append("(" + (" /\\ ".join(conj) if conj else "TRUE") + ")")
    return f"{name}(F) == " + " \\/ ".join(alts)


def _bexpr(parts):
    if not parts:
        return "[f \\in ModeSet |-> 0]"
    return "[f \\in ModeSet |-> CASE " + " [] ".join(f'f = "{f}" -> {x}' for f, x in parts) + " [] OTHER -> 0]"


def port_key(comp, port):
    """The name of an input port's queue in the module."""
    return f"{_ident(comp)}__{_ident(port)}"


def module_for(m, cone, want=({},), done=(), schedule=None, name="Cone"):
    """want: pin sets whose switch vectors this run must cover; done: pin sets already covered
    (their vectors are skipped). Returns (module text, cfg text)."""
    from ..model.cone import default_schedule
    for e in cone.edges:
        if not _ID.match(e):
            raise ValueError(f"edge id {e!r} must be an identifier")
    build = {"fifo": _fifo_module, "rounds": _rounds_module}[schedule or m.schedule or default_schedule()]
    return build(m, cone, want, done, name)


def _common(m, cone, want, done, name):
    """The lines both translators start with."""
    fields = list(cone.fields)
    ucs = [u for u in m.use_cases if u.id in cone.use_cases]
    vec_rows = list(cone.rows)
    L = [f"---------------------------- MODULE {name} ----------------------------",
         f"\\* Generated by epa.translate.to_tla for observation point {cone.obs}.",
         "\\* Cells: " + ", ".join(c.id for c in cone.cells),
         "EXTENDS Naturals, FiniteSets, Sequences, EpaLib", ""]
    L.append(f"ModeSet == {_set(fields)}")
    L.append(f"ATop == {m.auth_top}")
    L.append("T0 == [b |-> [f \\in ModeSet |-> 0], c |-> 0, a |-> ATop, t |-> 0]")
    L.append("NoMsg == [u |-> FALSE, n |-> FALSE, k |-> T0]")
    L.append(f"Edges == {_set(cone.edges)}")
    L.append(f"VecRows == {_set(vec_rows)}")
    L.append(f"UseCases == {_set([u.id for u in ucs])}")
    L.append(_vector_pred("Want", list(want), vec_rows))
    L.append(_vector_pred("Done", list(done), vec_rows))
    L.append("Vectors == {F \\in SUBSET VecRows : Want(F) /\\ ~Done(F)}")
    L.append("")
    return L, fields, ucs


def _tok_expr(tok, fields, track=None):
    parts = [(f, str(tok["b"].get(f, 0))) for f in fields if tok["b"].get(f, 0)]
    track = track or {"c": True, "a": True, "t": True}
    return (f"[b |-> {_bexpr(parts)}, c |-> {tok['c'] if track['c'] else 0}, "
            f"a |-> {tok['a'] if track['a'] else 'ATop'}, t |-> {tok['t'] if track['t'] else 0}]")


def _rounds_module(m, cone, want, done, name):
    L, fields, ucs = _common(m, cone, want, done, name)
    comps = [m.components[c] for c in cone.components]
    edge_ids = list(cone.edges)
    always = set(cone.always)
    in_cone = set(cone.rows) | always
    starts = []
    for u in ucs:
        ents = [(eid, tok) for eid, tok in u.entries if eid in edge_ids]
        body = "[e \\in Edges |-> " + "".join(
            f'IF e = "{eid}" THEN [u |-> TRUE, n |-> TRUE, k |-> {_tok_expr(tok, fields)}] ELSE ' for eid, tok in ents
        ) + "NoMsg]"
        starts.append(f'x = "{u.id}" -> {body}')
    L.append("Start(x) == CASE " + "\n             [] ".join(starts))
    strata = guard_strata(m, cone)
    L.append(f"MaxPhase == {max(strata.values() or [0])}")
    L.append("")

    for c in comps:
        _component(m, c, cone, fields, always, in_cone, L, strata.get(c.id, 0))

    # ---- one round: every component once, merged into its output edges
    lets = [f"o_{_ident(c.id)} == Outs_{_ident(c.id)}(lab, F, ph)" for c in comps]
    cases, fired = [], []
    for e in edge_ids:
        src = m.edges[e].src
        if src[0] == "sys" or src[0] not in cone.components:
            continue
        cases.append(f'e = "{e}" -> MergeLab(lab[e], o_{_ident(src[0])}.{_ident(src[1])})')
    for c in comps:
        fired.append(f"o_{_ident(c.id)}.fired")
    L.append("Step(lab, F, ph) ==")
    L.append("  LET " + "\n      ".join(lets) if lets else "  LET dummy == 0")
    L.append("  IN [lab |-> [e \\in Edges |-> CASE " + "\n                          [] ".join(cases + ["OTHER -> lab[e]"]) + "],")
    L.append("      fired |-> " + (" \\cup ".join(fired) if fired else "{}") + "]")
    L.append("")
    L.append("VARIABLES uc, fire, lab, fired, rnd, done, phase")
    L.append("vars == <<uc, fire, lab, fired, rnd, done, phase>>")
    L.append("Init == /\\ uc \\in UseCases /\\ fire \\in Vectors /\\ lab = Start(uc)")
    L.append("        /\\ fired = {} /\\ rnd = 0 /\\ done = FALSE /\\ phase = 0")
    L.append("\\* A round. A guard that may drop a message acts only from its phase on, once everything upstream")
    L.append("\\* of it has settled; a round that changes nothing opens the next phase, and in the last phase it")
    L.append("\\* marks the least fixpoint (done) and records which rows fire on the final labels.")
    L.append("Round == /\\ ~done")
    L.append("         /\\ LET s == Step(lab, fire, phase) IN")
    L.append("              /\\ lab' = s.lab /\\ fired' = s.fired")
    L.append("              /\\ IF s.lab = lab")
    L.append("                   THEN IF phase = MaxPhase THEN done' = TRUE /\\ phase' = phase")
    L.append("                        ELSE done' = FALSE /\\ phase' = phase + 1")
    L.append("                   ELSE done' = FALSE /\\ phase' = phase")
    L.append("         /\\ rnd' = rnd + 1 /\\ UNCHANGED <<uc, fire>>")
    L.append("Next == Round")
    L.append("Spec == Init /\\ [][Next]_vars")
    L.append("=============================================================================")
    return "\n".join(L) + "\n", "SPECIFICATION Spec\nCHECK_DEADLOCK FALSE\n"


def _tracked(m, cone, in_cone):
    """Which provenance fields, and the normal bit, the tokens of this cone need. A field no cell of the
    cone reads and no guard of the cone tests can change nothing the cone decides, so it stays constant
    and two tokens that differ only there are one token value."""
    kinds = {c.kind for c in cone.cells}
    guards = [m.components[c] for c in cone.components if m.components[c].is_guard]
    tested = {t["kind"] for g in guards for t in g.targets if t["row"] in in_cone}
    droppers = any(not g.on_cycle and any(t["row"] in in_cone for t in g.targets) for g in guards)
    return {"c": "conf" in kinds | tested, "a": "auth" in kinds | tested, "t": "taint" in kinds | tested,
            "n": droppers}


def _solo(m, cone, comps, ready):
    """For each component c, the condition under which firing c now cannot interact with anything that
    can happen before it, so that it alone is explored from this state (docs/dev/alethic.md, section 5:
    a persistent set of one). `ready[d]` is the text of d's readiness."""
    ids = [c.id for c in comps]
    succ = {c: set() for c in ids}
    srcs = {}
    for e in cone.edges:
        s, d = m.edges[e].src[0], m.edges[e].dst
        if s in succ and d[0] in succ:
            succ[s].add(d[0])
            srcs.setdefault(d, set()).add(s)

    def reach(start, avoid):
        seen, stack = set(), [start]
        while stack:
            x = stack.pop()
            if x == avoid or x in seen:
                continue
            seen.add(x)
            stack += list(succ[x])
        return seen
    out = {}
    for c in comps:
        conj = [ready[c.id]]
        for d in ids:
            if d == c.id:
                continue
            r = reach(d, c.id)
            if (succ[c.id] - {c.id}) & r:
                conj.append(f"~({ready[d]})")
                continue
            need = [f'q["{port_key(c.id, p)}"] # <<>>' for p in c.ins if srcs.get((c.id, p), set()) & r]
            if need:
                conj.append(f"(({ready[d]}) => (" + " /\\ ".join(need) + "))")
        out[c.id] = " /\\ ".join(f"({x})" for x in conj)
    return out


def _fifo_module(m, cone, want, done, name):
    L, fields, ucs = _common(m, cone, want, done, name)
    comps = [m.components[c] for c in cone.components]
    always = set(cone.always)
    in_cone = set(cone.rows) | always
    track = _tracked(m, cone, in_cone)
    in_cone_edges = set(cone.edges)
    ports = [port_key(c.id, p) for c in comps for p in c.ins
             if any(e.id in in_cone_edges for e in m.edges_into(c.id, p))]
    L.append(f"Ports == {_set(ports)}")

    def queue_of(eid):
        d = m.edges[eid].dst
        return port_key(*d) if d[0] in cone.components else ""

    # ---- the starting tokens: on the edges leaving the system input, already delivered
    starts = []
    for u in ucs:
        ents = [(eid, tok) for eid, tok in u.entries if eid in in_cone_edges]
        msg = {eid: f"[n |-> TRUE, k |-> {_tok_expr(tok, fields, track)}]" for eid, tok in ents}
        at = {}
        for eid, _ in ents:
            if queue_of(eid):
                at.setdefault(queue_of(eid), []).append(msg[eid])
        qs = "[p \\in Ports |-> " + "".join(f'IF p = "{p}" THEN <<{", ".join(ms)}>> ELSE ' for p, ms in at.items()) + "<<>>]"
        seen = "[e \\in Edges |-> " + "".join(f'IF e = "{e}" THEN {{{x}}} ELSE ' for e, x in msg.items()) + "{}]"
        lab = "[e \\in Edges |-> " + "".join(
            f'IF e = "{e}" THEN [u |-> TRUE, n |-> TRUE, k |-> {x}.k] ELSE ' for e, x in msg.items()) + "NoMsg]"
        starts.append(f'x = "{u.id}" -> [q |-> {qs},\n      seen |-> {seen},\n      lab |-> {lab}]')
    L.append("Start(x) == CASE " + "\n             [] ".join(starts))
    L.append("")
    L.append("VARIABLES uc, fire, q, seen, lab, fired, spent, done")
    L.append("vars == <<uc, fire, q, seen, lab, fired, spent, done>>")
    L.append("")

    ready = {}
    for c in comps:
        terms = [f'Q["{port_key(c.id, p)}"] # <<>>' for p in c.ins if port_key(c.id, p) in ports]
        for r in m.comp_rows(c.id):
            if r.id in in_cone and not r.when and r.kind == "row":
                on = "" if r.id in always else f'"{r.id}" \\in fire /\\ '
                terms.append(f'({on}~("{r.id}" \\in S))')
        ready[c.id] = " \\/ ".join(terms) or "FALSE"
    for c in comps:
        _component(m, c, cone, fields, always, in_cone, L, track=track)
        L.append(f"Ready_{_ident(c.id)}(Q, S) == {ready[c.id]}")
    L.append("Quiet(Q, S) == " + (" /\\ ".join(f"~Ready_{_ident(c.id)}(Q, S)" for c in comps) or "TRUE"))
    L.append("")
    L.append("\\* One firing: the heads leave their queues, each output port written delivers on its edges, and")
    L.append("\\* the run is done when nothing is ready any more. Nothing outside the queues remembers a firing.")
    L.append("Commit(s, o) == /\\ q' = s.q /\\ seen' = s.seen /\\ lab' = s.lab")
    L.append("                /\\ fired' = fired \\cup o.fired /\\ spent' = spent \\cup o.spent")
    L.append("                /\\ done' = Quiet(s.q, spent \\cup o.spent) /\\ UNCHANGED <<uc, fire>>")
    L.append("")
    for c in comps:
        cid = _ident(c.id)
        lets = [f"o == Outs_{cid}(q, fire, spent)"]
        mine = [port_key(c.id, p) for p in c.ins if port_key(c.id, p) in ports]
        lets.append(f"s0 == [q |-> Pop(q, {_set(mine)}), seen |-> seen, lab |-> lab]")
        n = 0
        for e in cone.edges:
            src = m.edges[e].src
            if src[0] == c.id:
                lets.append(f's{n + 1} == Deliver(s{n}, "{e}", "{queue_of(e)}", o.p_{_ident(src[1])})')
                n += 1
        L.append(f"Fire_{cid} ==")
        L.append(f"  /\\ Ready_{cid}(q, spent)")
        L.append("  /\\ LET " + "\n         ".join(lets))
        L.append(f"     IN Commit(s{n}, o)")
        L.append("")
    L.append("Init == /\\ uc \\in UseCases /\\ fire \\in Vectors")
    L.append("        /\\ LET s == Start(uc) IN q = s.q /\\ seen = s.seen /\\ lab = s.lab")
    L.append("        /\\ fired = {} /\\ spent = {} /\\ done = Quiet(q, spent)")
    fires = [f"Fire_{_ident(c.id)}" for c in comps]
    every = " \\/ ".join(fires) or "FALSE"
    if os.environ.get("EPA_POR", "1") == "0":
        L.append(f"Next == {every}")
    else:
        solo = _solo(m, cone, comps, {c.id: f"Ready_{_ident(c.id)}(q, spent)" for c in comps})
        for c in comps:
            L.append(f"Solo_{_ident(c.id)} == {solo[c.id]}")
        L.append("\\* Fire a component that interacts with nothing else that can happen first; only if there is")
        L.append("\\* none, branch on every ready component.")
        L.append("Next == " + "".join(f"IF Solo_{_ident(c.id)} THEN Fire_{_ident(c.id)}\n        ELSE " for c in comps) + every)
    L.append("Spec == Init /\\ [][Next]_vars /\\ WF_vars(Next)")
    L.append("=============================================================================")
    return "\n".join(L) + "\n", "SPECIFICATION Spec\nCHECK_DEADLOCK FALSE\n"


def guard_strata(m, cone):
    """The phase from which each guard that may drop a message acts: one more than the guards of that
    kind upstream of it, so that it reads its input only once everything upstream has settled (the
    stratified fixpoint of the propagation property). Guards on a cycle never drop and act always."""
    from ..model.cone import normal_edges, possible, upstream
    if not hasattr(m, "_possible"):
        m._normal_edges = normal_edges(m)
        m._possible = possible(m)

    def may_drop(g):
        # a guard drops only a message that no forwarding sent: if, in every use case, whatever reaches
        # it is a normal message, it never drops and needs no phase of its own
        for u in cone.use_cases:
            for e in m.edges_into(g, "in"):
                if e.id in m._possible[u] and e.id not in m._normal_edges[u]:
                    return True
        return False
    droppers = [c for c in cone.components if m.components[c].is_guard and not m.components[c].on_cycle
                and may_drop(c)]
    memo = {}

    def s(g):
        if g not in memo:
            memo[g] = 0
            up = set()
            for e in m.edges_into(g, "in"):
                up |= upstream(m, e.id)
            memo[g] = 1 + max([s(x) for x in droppers if x != g and x in up] or [0])
        return memo[g]
    return {g: s(g) for g in droppers}


def _fp_magnitude(c, fifo):
    """The omission a learned guard's false positive causes: as declared, else present (rounds: 10)."""
    from ..model.defaults import PRESENT, ROUNDS_TOP
    if c.fp_omission is not None:
        return c.fp_omission
    return (PRESENT if fifo else ROUNDS_TOP) if c.learned else 0


def _component(m, c, cone, fields, always, in_cone, L, stratum=0, track=None):
    """The operator Outs_<c>: what c sends on each output port and which rows applied. Under rounds it
    reads the edge labels (`lab`), under fifo (`track` given) the heads of its queues (`Q`)."""
    from ..model.cone import forwarding
    from ..model.defaults import ROUNDS_TOP
    fifo = track is not None
    cid = _ident(c.id)
    edge_ids = set(cone.edges)
    in_edges = {p: [e.id for e in m.edges_into(c.id, p) if e.id in edge_ids] for p in c.ins}
    lets = []
    for p, es in in_edges.items():
        P = _ident(p)
        if not es:
            lets += [f"u_{P} == FALSE", f"n_{P} == FALSE", f"i_{P} == T0"]
            continue
        if fifo:
            k = f'Q["{port_key(c.id, p)}"]'
            lets += [f"u_{P} == {k} # <<>>", f"n_{P} == u_{P} /\\ Head({k}).n",
                     f"i_{P} == IF u_{P} THEN Head({k}).k ELSE T0"]
            continue
        lets.append(f"u_{P} == " + " \\/ ".join(f'lab["{e}"].u' for e in es))
        lets.append(f"n_{P} == " + " \\/ ".join(f'(lab["{e}"].u /\\ lab["{e}"].n)' for e in es))
        if len(es) == 1:
            lets.append(f'i_{P} == IF lab["{es[0]}"].u THEN lab["{es[0]}"].k ELSE T0')
        else:
            lets.append(f"i_{P} == JoinAll({{lab[e].k : e \\in {{e \\in {_set(es)} : lab[e].u}}}}, T0)")
    all_in = sorted({e for es in in_edges.values() for e in es})
    if fifo:
        joined = "T0"
        for p, es in reversed(list(in_edges.items())):
            if es:
                joined = f"i_{_ident(p)}" if joined == "T0" else f"JoinTok(i_{_ident(p)}, {joined})"
        lets.append(f"all == {joined}")
    elif len(all_in) > 1:
        lets.append(f"all == JoinAll({{lab[e].k : e \\in {{e \\in {_set(all_in)} : lab[e].u}}}}, T0)")
    elif all_in:
        lets.append(f"all == i_{_ident(next(p for p, es in in_edges.items() if es))}")
    else:
        lets.append("all == T0")

    def eff(tok, mode):
        fam = [f for f in m.family(mode) if f in fields]
        if not fam:
            return "0"
        if len(fam) == 1:
            return f'{tok}.b["{fam[0]}"]'
        return "MaxSet({" + ", ".join(f'{tok}.b["{f}"]' for f in fam) + "})"

    fired_terms, spent_terms = [], []
    outs = {}
    field_of = (lambda qp: f"p_{_ident(qp)}") if fifo else _ident
    keep_c = "all.c" if not fifo or track["c"] else "0"
    keep_t = lambda level: ("0" if fifo and not track["t"] else f"Max(all.t, {level})" if level else "all.t")  # noqa: E731
    if c.is_guard:
        tin = "i_in"
        caught = []
        for t in c.targets:
            rid = t["row"]
            if rid not in in_cone:
                continue
            R = _ident(rid)
            lets_through = "TRUE" if rid in always else f'"{rid}" \\in F'
            if t["kind"] == "mode":
                present = f"{eff(tin, t['mode'])} >= {t['threshold']}"
            elif t["kind"] == "taint":
                present = f"{tin}.t >= {t['level']}"
            elif t["kind"] == "conf":
                present = f"{tin}.c > {t['level']}"
            else:
                present = f"{tin}.a < {t['level']}"
            lets.append(f"p_{R} == u_in /\\ {present}")
            lets.append(f"f_{R} == p_{R} /\\ {lets_through}")
            lets.append(f"c_{R} == p_{R} /\\ ~({lets_through})")
            if rid not in always:
                fired_terms.append((rid, f"f_{R}"))
            caught.append((t, f"c_{R}"))
        fp = f"fp.{c.id}"
        has_fp = fp in in_cone and "omission" in fields
        if fp in in_cone:
            lets.append(f"f_{_ident(fp)} == u_in /\\ " + ("TRUE" if fp in always else f'"{fp}" \\in F'))
            if fp not in always:
                fired_terms.append((fp, f"f_{_ident(fp)}"))
        parts = []
        for f in fields:
            v = f'{tin}.b["{f}"]'
            for t, cond in caught:
                if t["kind"] == "mode" and f in m.family(t["mode"]):
                    v = f"IF {cond} THEN 0 ELSE {v}" if fifo else f"IF {cond} THEN Min({v}, {t['threshold'] - 1}) ELSE {v}"
            if f == "omission" and has_fp:
                v = f"IF f_{_ident(fp)} THEN Max({v}, {_fp_magnitude(c, fifo)}) ELSE {v}"
            parts.append((f, f"({v})"))
        cexpr, aexpr, texpr = f"{tin}.c", f"{tin}.a", f"{tin}.t"
        for t, cond in caught:
            if t["kind"] == "conf":
                cexpr = f"IF {cond} THEN {t['level']} ELSE {cexpr}"
            elif t["kind"] == "auth":
                aexpr = f"IF {cond} THEN {t['level']} ELSE {aexpr}"
            elif t["kind"] == "taint":
                texpr = f"IF {cond} THEN {t['level'] - 1} ELSE {texpr}"
        any_caught = " \\/ ".join(cd for _, cd in caught) or "FALSE"
        drop = "FALSE" if c.on_cycle else f"(~n_in /\\ ({any_caught}))"
        lets.append(f"drop == {drop}")
        # a guard that may drop acts only from its phase on, when its input has settled
        acts = f"ph >= {stratum} /\\ " if stratum else ""
        if fifo:
            cexpr, aexpr, texpr = (cexpr if track["c"] else "0", aexpr if track["a"] else "ATop",
                                   texpr if track["t"] else "0")
        nexpr = "n_in" if not fifo or track["n"] else "TRUE"
        outs["out"] = (f"[u |-> {acts}u_in /\\ ~drop, n |-> {nexpr}, k |-> [b |-> {_bexpr(parts)}, "
                       f"c |-> {cexpr}, a |-> {aexpr}, t |-> {texpr}]]")
    else:
        rows = [m.rows[r] for r in sorted(in_cone) if m.rows[r].comp == c.id]
        for r in rows:
            R = _ident(r.id)
            conds, mags = [], []
            if "*" in r.when:
                conds.append("(" + (" \\/ ".join(f"u_{_ident(p)}" for p in c.ins) or "FALSE") + ")")
            else:
                for p, pat in r.when.items():
                    P = _ident(p)
                    conds.append(f"u_{P}")
                    for f, th in pat.get("modes", {}).items():
                        e = eff(f"i_{P}", f)
                        conds.append(f"{e} >= {th}")
                        mags.append(e)
            # an internal fault needs no incoming message; under fifo it applies at most once per run
            once = f'~("{r.id}" \\in S)' if fifo else "TRUE"
            lets.append(f"m_{R} == " + (" /\\ ".join(conds) if conds else once))
            if fifo and not r.when and r.kind == "row":
                spent_terms.append((r.id, f"f_{R}"))
            if mags:
                lets.append(f"v_{R} == " + ("MaxSet({" + ", ".join(mags) + "})" if len(mags) > 1 else mags[0]))
            if r.id in always:
                lets.append(f"f_{R} == m_{R}")
            else:
                lets.append(f'f_{R} == m_{R} /\\ "{r.id}" \\in F')
                fired_terms.append((r.id, f"f_{R}"))
        sinks = [r for r in rows if r.kind == "sink"]

        def sunk(p, f):
            """A sink row at port p that matches f absorbs it in this round."""
            cs = [f"f_{_ident(s.id)}" for s in sinks if any(f in m.family(g) for g in s.when.get(p, {}).get("modes", {}))]
            return " \\/ ".join(cs)

        auth_out = f"{c.authority}" if c.raises else f"Min({c.authority}, all.a)"
        if fifo and not track["a"]:
            auth_out = "ATop"
        # rounds keeps the old boolean: only `trusted: false`, or an external or user component, taints
        taint_out = keep_t(c.taint if fifo else (0 if c.trusted else 1))
        fwds = [(ports, q, r, join) for ports, q, r, join in forwarding(m, c) if r is None or r.id in in_cone]
        for qp in c.outs:
            if fifo and not any(e.id in edge_ids for e in m.edges_from(c.id, qp)):
                continue
            mine = [(ports, r, join) for ports, q, r, join in fwds if q == qp]
            sent, norm = [], []
            for ports, r, join in mine:
                if r is None:
                    sent.append(f"u_{_ident(ports[0])}")
                    norm.append(f"n_{_ident(ports[0])}")
                else:
                    sent.append(f"f_{_ident(r.id)}")
                    if r.kind == "fwd":
                        nj = (" \\/ " if join == "any" else " /\\ ").join(f"n_{_ident(p)}" for p in ports)
                        norm.append(f"(f_{_ident(r.id)} /\\ ({nj or 'FALSE'}))")
            emitting = [r for r in rows if qp in r.then and r.kind in ("row", "default")]
            sent += [f"f_{_ident(r.id)}" for r in emitting]
            sent_x = " \\/ ".join(dict.fromkeys(sent)) or "FALSE"
            norm_x = " \\/ ".join(norm) or "FALSE"
            parts = []
            for f in fields:
                terms = []
                for ports, r, join in mine:
                    gate = "" if r is None else f"f_{_ident(r.id)} /\\ "
                    for p in ports:
                        if f not in c.passes.get(p, []):
                            continue
                        sk = sunk(p, f)
                        cond = f"{gate}u_{_ident(p)}" + (f" /\\ ~({sk})" if sk else "")
                        terms.append(f'IF {cond} THEN i_{_ident(p)}.b["{f}"] ELSE 0')
                for r in emitting:
                    if f in r.then[qp]:
                        op, k = r.then[qp][f]
                        R = _ident(r.id)
                        if r.kind == "default" and not fifo:
                            k = ROUNDS_TOP
                        val = {"const": str(k), "keep": f"v_{R}", "max": f"v_{R}", "plus": f"Sat(v_{R} + {k})"}[op]
                        terms.append(f"IF f_{R} THEN {val} ELSE 0")
                terms = list(dict.fromkeys(terms))
                if len(terms) == 1:
                    parts.append((f, f"({terms[0]})"))
                elif terms:
                    parts.append((f, "MaxSet({" + ", ".join(terms) + "})"))
            if fifo and not track["n"]:
                norm_x = "TRUE"
            outs[qp] = (f"[u |-> {sent_x}, n |-> {norm_x}, k |-> [b |-> {_bexpr(parts)}, "
                        f"c |-> {keep_c}, a |-> {auth_out}, t |-> {taint_out}]]")
    fired = " \\cup ".join(f'(IF {x} THEN {{"{rid}"}} ELSE {{}})' for rid, x in fired_terms) or "{}"
    rec = ",\n         ".join(f"{field_of(qp)} |-> {v}" for qp, v in outs.items())
    L.append(f"\\* {c.kind} {c.id}" + (f" (guard on {c.on_edge}{', on a cycle' if c.on_cycle else ''}"
                                        f"{f', acts from phase {stratum}' if stratum else ''})" if c.is_guard else ""))
    L.append(f"Outs_{cid}(Q, F, S) ==" if fifo else f"Outs_{cid}(lab, F, ph) ==")
    L.append("  LET " + "\n      ".join(lets))
    if fifo:
        spent = " \\cup ".join(f'(IF {x} THEN {{"{rid}"}} ELSE {{}})' for rid, x in spent_terms) or "{}"
        L.append(f"  IN [{rec + ',' if rec else ''}\n         fired |-> {fired},\n         spent |-> {spent}]")
    else:
        L.append(f"  IN [{rec},\n         fired |-> {fired}]")
    L.append("")
