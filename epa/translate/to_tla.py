"""Translate one cone into a TLA+ module whose behaviours are the runs of the alethic layer.

A run is a use case together with a firing choice: for every row of the cone whose activation is
open, whether it fires (the paper's definition of a run). The firing choice is part of the initial
state, so one TLC run explores every use case and every firing choice of the cone at once. From there
the module propagates the use case's starting tokens round by round: in a round every component
recomputes what it sends from what it receives, and the result is merged into its output edges.
When a round changes nothing the run has reached its least fixpoint and stops (`done`).

Candidates are not in the module: a candidate *admits* a run when its never rows are not in the
firing choice and its always rows are, so the epistemic layer reads every candidate's runs off the
same explored states.

The text is deterministic: the same model, cone and options give the same file, which is what the
run cache keys on.
"""
from __future__ import annotations

import re

_ID = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def q(s):
    return '"' + s + '"'


def _set(xs):
    return "{" + ", ".join(q(x) for x in xs) + "}"


def _ident(s):
    return re.sub(r"[^A-Za-z0-9_]", "_", s)


def _vector_pred(name, pin_sets, vec_rows):
    """A predicate over firing choices F: F agrees with at least one of the pin sets.
    A pin set maps rows to 'N' (must not fire) or 'A' (must fire)."""
    if not pin_sets:
        return f"{name}(F) == FALSE"
    alts = []
    for pins in pin_sets:
        a = sorted(r for r, x in pins.items() if x == "A" and r in vec_rows)
        n = sorted(r for r, x in pins.items() if x == "N" and r in vec_rows)
        conj = []
        if a:
            conj.append(f"{_set(a)} \\subseteq F")
        if n:
            conj.append(f"F \\cap {_set(n)} = {{}}")
        alts.append("(" + (" /\\ ".join(conj) if conj else "TRUE") + ")")
    return f"{name}(F) == " + " \\/ ".join(alts)


def _bexpr(parts):
    if not parts:
        return "[f \\in ModeSet |-> 0]"
    return "[f \\in ModeSet |-> CASE " + " [] ".join(f'f = "{f}" -> {x}' for f, x in parts) + " [] OTHER -> 0]"


def module_for(m, cone, want=({},), done=(), schedule="rounds", name="Cone"):
    """want: pin sets whose firing choices this run must cover; done: pin sets already covered
    (their firing choices are skipped). Returns (module text, cfg text)."""
    fields = list(cone.fields)
    comps = [m.components[c] for c in cone.components]
    edge_ids = list(cone.edges)
    for e in edge_ids:
        if not _ID.match(e):
            raise ValueError(f"edge id {e!r} must be an identifier")
    vec_rows = list(cone.rows)
    always = set(cone.always)
    in_cone = set(vec_rows) | always
    ucs = [u for u in m.use_cases if u.id in cone.use_cases]

    L = [f"---------------------------- MODULE {name} ----------------------------",
         f"\\* Generated by epa.translate.to_tla for observation point {cone.obs}.",
         "\\* Cells: " + ", ".join(c.id for c in cone.cells),
         "EXTENDS Naturals, FiniteSets, EpaLib", ""]
    L.append(f"ModeSet == {_set(fields)}")
    L.append(f"ATop == {m.auth_top}")
    L.append("T0 == [b |-> [f \\in ModeSet |-> 0], c |-> 0, a |-> ATop, t |-> FALSE]")
    L.append("NoMsg == [u |-> FALSE, n |-> FALSE, k |-> T0]")
    L.append(f"Edges == {_set(edge_ids)}")
    L.append(f"VecRows == {_set(vec_rows)}")
    L.append(f"UseCases == {_set([u.id for u in ucs])}")
    L.append(_vector_pred("Want", list(want), vec_rows))
    L.append(_vector_pred("Done", list(done), vec_rows))
    L.append("Vectors == {F \\in SUBSET VecRows : Want(F) /\\ ~Done(F)}")
    L.append("")

    def tok_expr(tok):
        parts = [(f, str(tok["b"].get(f, 0))) for f in fields if tok["b"].get(f, 0)]
        return (f"[b |-> {_bexpr(parts)}, c |-> {tok['c']}, a |-> {tok['a']}, "
                f"t |-> {'TRUE' if tok['t'] else 'FALSE'}]")

    starts = []
    for u in ucs:
        ents = [(eid, tok) for eid, tok in u.entries if eid in edge_ids]
        body = "[e \\in Edges |-> " + "".join(
            f'IF e = "{eid}" THEN [u |-> TRUE, n |-> TRUE, k |-> {tok_expr(tok)}] ELSE ' for eid, tok in ents
        ) + "NoMsg]"
        starts.append(f'x = "{u.id}" -> {body}')
    L.append("Start(x) == CASE " + "\n             [] ".join(starts))
    strata = guard_strata(m, cone)
    L.append(f"MaxPhase == {max(strata.values() or [0])}")
    L.append("")

    for c in comps:
        _component(m, c, cone, fields, vec_rows, always, in_cone, L, strata.get(c.id, 0))

    # ---- one round: every component once, merged into its output edges
    lets = [f"o_{_ident(c.id)} == Outs_{_ident(c.id)}(lab, F, ph)" for c in comps]
    cases, fired = [], []
    for e in edge_ids:
        src = m.edges[e].src
        if src[0] == "sys" or src[0] not in cone.components:
            continue
        cases.append(f'e = "{e}" -> MergeLab(lab[e], o_{_ident(src[0])}.{_ident(src[1])})')
    for c in comps:
        fired.append(f"o_{_ident(c.id)}.fired")
    L.append("Step(lab, F, ph) ==")
    L.append("  LET " + "\n      ".join(lets) if lets else "  LET dummy == 0")
    L.append("  IN [lab |-> [e \\in Edges |-> CASE " + "\n                          [] ".join(cases + ["OTHER -> lab[e]"]) + "],")
    L.append("      fired |-> " + (" \\cup ".join(fired) if fired else "{}") + "]")
    L.append("")
    L.append("VARIABLES uc, fire, lab, fired, rnd, done, phase")
    L.append("vars == <<uc, fire, lab, fired, rnd, done, phase>>")
    L.append("Init == /\\ uc \\in UseCases /\\ fire \\in Vectors /\\ lab = Start(uc)")
    L.append("        /\\ fired = {} /\\ rnd = 0 /\\ done = FALSE /\\ phase = 0")
    L.append("\\* A round. A guard that may drop a message acts only from its phase on, once everything upstream")
    L.append("\\* of it has settled; a round that changes nothing opens the next phase, and in the last phase it")
    L.append("\\* marks the least fixpoint (done) and records which rows fire on the final labels.")
    L.append("Round == /\\ ~done")
    L.append("         /\\ LET s == Step(lab, fire, phase) IN")
    L.append("              /\\ lab' = s.lab /\\ fired' = s.fired")
    L.append("              /\\ IF s.lab = lab")
    L.append("                   THEN IF phase = MaxPhase THEN done' = TRUE /\\ phase' = phase")
    L.append("                        ELSE done' = FALSE /\\ phase' = phase + 1")
    L.append("                   ELSE done' = FALSE /\\ phase' = phase")
    L.append("         /\\ rnd' = rnd + 1 /\\ UNCHANGED <<uc, fire>>")
    L.append("Next == Round")
    L.append("Spec == Init /\\ [][Next]_vars")
    L.append("=============================================================================")
    cfg = "SPECIFICATION Spec\nCHECK_DEADLOCK FALSE\n"
    return "\n".join(L) + "\n", cfg


def guard_strata(m, cone):
    """The phase from which each guard that may drop a message acts: one more than the guards of that
    kind upstream of it, so that it reads its input only once everything upstream has settled (the
    stratified fixpoint of the propagation property). Guards on a cycle never drop and act always."""
    from ..model.cone import normal_edges, possible, upstream
    if not hasattr(m, "_possible"):
        m._normal_edges = normal_edges(m)
        m._possible = possible(m)

    def may_drop(g):
        # a guard drops only a message that no forwarding sent: if, in every use case, whatever reaches
        # it is a normal message, it never drops and needs no phase of its own
        for u in cone.use_cases:
            for e in m.edges_into(g, "in"):
                if e.id in m._possible[u] and e.id not in m._normal_edges[u]:
                    return True
        return False
    droppers = [c for c in cone.components if m.components[c].is_guard and not m.components[c].on_cycle
                and may_drop(c)]
    memo = {}

    def s(g):
        if g not in memo:
            memo[g] = 0
            up = set()
            for e in m.edges_into(g, "in"):
                up |= upstream(m, e.id)
            memo[g] = 1 + max([s(x) for x in droppers if x != g and x in up] or [0])
        return memo[g]
    return {g: s(g) for g in droppers}


def _component(m, c, cone, fields, vec_rows, always, in_cone, L, stratum=0):
    from ..model.cone import forwarding
    cid = _ident(c.id)
    edge_ids = set(cone.edges)
    in_edges = {p: [e.id for e in m.edges_into(c.id, p) if e.id in edge_ids] for p in c.ins}
    lets = []
    for p, es in in_edges.items():
        P = _ident(p)
        if not es:
            lets += [f"u_{P} == FALSE", f"n_{P} == FALSE", f"i_{P} == T0"]
            continue
        lets.append(f"u_{P} == " + " \\/ ".join(f'lab["{e}"].u' for e in es))
        lets.append(f"n_{P} == " + " \\/ ".join(f'(lab["{e}"].u /\\ lab["{e}"].n)' for e in es))
        if len(es) == 1:
            lets.append(f'i_{P} == IF lab["{es[0]}"].u THEN lab["{es[0]}"].k ELSE T0')
        else:
            lets.append(f"i_{P} == JoinAll({{lab[e].k : e \\in {{e \\in {_set(es)} : lab[e].u}}}}, T0)")
    all_in = sorted({e for es in in_edges.values() for e in es})
    if len(all_in) > 1:
        lets.append(f"all == JoinAll({{lab[e].k : e \\in {{e \\in {_set(all_in)} : lab[e].u}}}}, T0)")
    elif all_in:
        lets.append(f"all == i_{_ident(next(p for p, es in in_edges.items() if es))}")
    else:
        lets.append("all == T0")

    def eff(tok, mode):
        fam = [f for f in m.family(mode) if f in fields]
        if not fam:
            return "0"
        if len(fam) == 1:
            return f'{tok}.b["{fam[0]}"]'
        return "MaxSet({" + ", ".join(f'{tok}.b["{f}"]' for f in fam) + "})"

    fired_terms = []
    outs = {}
    if c.is_guard:
        tin = "i_in"
        caught = []
        for t in c.targets:
            rid = t["row"]
            if rid not in in_cone:
                continue
            R = _ident(rid)
            lets_through = "TRUE" if rid in always else f'"{rid}" \\in F'
            if t["kind"] == "mode":
                present = f"{eff(tin, t['mode'])} >= {t['threshold']}"
            elif t["kind"] == "taint":
                present = f"{tin}.t"
            elif t["kind"] == "conf":
                present = f"{tin}.c > {t['level']}"
            else:
                present = f"{tin}.a < {t['level']}"
            lets.append(f"p_{R} == u_in /\\ {present}")
            lets.append(f"f_{R} == p_{R} /\\ {lets_through}")
            lets.append(f"c_{R} == p_{R} /\\ ~({lets_through})")
            if rid not in always:
                fired_terms.append((rid, f"f_{R}"))
            caught.append((t, f"c_{R}"))
        fp = f"fp.{c.id}"
        has_fp = fp in in_cone and "omission" in fields
        if fp in in_cone:
            lets.append(f"f_{_ident(fp)} == u_in /\\ " + ("TRUE" if fp in always else f'"{fp}" \\in F'))
            if fp not in always:
                fired_terms.append((fp, f"f_{_ident(fp)}"))
        parts = []
        for f in fields:
            v = f'{tin}.b["{f}"]'
            for t, cond in caught:
                if t["kind"] == "mode" and f in m.family(t["mode"]):
                    v = f"IF {cond} THEN Min({v}, {t['threshold'] - 1}) ELSE {v}"
            if f == "omission" and has_fp:
                v = f"IF f_{_ident(fp)} THEN Max({v}, {c.fp_omission}) ELSE {v}"
            parts.append((f, f"({v})"))
        cexpr, aexpr, texpr = f"{tin}.c", f"{tin}.a", f"{tin}.t"
        for t, cond in caught:
            if t["kind"] == "conf":
                cexpr = f"IF {cond} THEN {t['level']} ELSE {cexpr}"
            elif t["kind"] == "auth":
                aexpr = f"IF {cond} THEN {t['level']} ELSE {aexpr}"
            elif t["kind"] == "taint":
                texpr = f"IF {cond} THEN FALSE ELSE {texpr}"
        any_caught = " \\/ ".join(cd for _, cd in caught) or "FALSE"
        drop = "FALSE" if c.on_cycle else f"(~n_in /\\ ({any_caught}))"
        lets.append(f"drop == {drop}")
        # a guard that may drop acts only from its phase on, when its input has settled
        acts = f"ph >= {stratum} /\\ " if stratum else ""
        outs["out"] = (f"[u |-> {acts}u_in /\\ ~drop, n |-> n_in, k |-> [b |-> {_bexpr(parts)}, "
                       f"c |-> {cexpr}, a |-> {aexpr}, t |-> {texpr}]]")
    else:
        rows = [m.rows[r] for r in sorted(in_cone) if m.rows[r].comp == c.id]
        for r in rows:
            R = _ident(r.id)
            conds, mags = [], []
            if "*" in r.when:
                conds.append("(" + (" \\/ ".join(f"u_{_ident(p)}" for p in c.ins) or "FALSE") + ")")
            else:
                for p, pat in r.when.items():
                    P = _ident(p)
                    conds.append(f"u_{P}")
                    for f, th in pat.get("modes", {}).items():
                        e = eff(f"i_{P}", f)
                        conds.append(f"{e} >= {th}")
                        mags.append(e)
            # an internal fault needs no incoming message
            lets.append(f"m_{R} == " + (" /\\ ".join(conds) if conds else "TRUE"))
            if mags:
                lets.append(f"v_{R} == " + ("MaxSet({" + ", ".join(mags) + "})" if len(mags) > 1 else mags[0]))
            if r.id in always:
                lets.append(f"f_{R} == m_{R}")
            else:
                lets.append(f'f_{R} == m_{R} /\\ "{r.id}" \\in F')
                fired_terms.append((r.id, f"f_{R}"))
        sinks = [r for r in rows if r.kind == "sink"]

        def sunk(p, f):
            """A sink row at port p that matches f absorbs it in this round."""
            cs = [f"f_{_ident(s.id)}" for s in sinks if any(f in m.family(g) for g in s.when.get(p, {}).get("modes", {}))]
            return " \\/ ".join(cs)

        auth_out = f"{c.authority}" if c.raises else f"Min({c.authority}, all.a)"
        taint_out = "TRUE" if not c.trusted else "all.t"
        fwds = [(ports, q, r, join) for ports, q, r, join in forwarding(m, c) if r is None or r.id in in_cone]
        for qp in c.outs:
            mine = [(ports, r, join) for ports, q, r, join in fwds if q == qp]
            sent, norm = [], []
            for ports, r, join in mine:
                if r is None:
                    sent.append(f"u_{_ident(ports[0])}")
                    norm.append(f"n_{_ident(ports[0])}")
                else:
                    sent.append(f"f_{_ident(r.id)}")
                    if r.kind == "fwd":
                        nj = (" \\/ " if join == "any" else " /\\ ").join(f"n_{_ident(p)}" for p in ports)
                        norm.append(f"(f_{_ident(r.id)} /\\ ({nj or 'FALSE'}))")
            emitting = [r for r in rows if qp in r.then and r.kind in ("row", "default")]
            sent += [f"f_{_ident(r.id)}" for r in emitting]
            sent_x = " \\/ ".join(dict.fromkeys(sent)) or "FALSE"
            norm_x = " \\/ ".join(norm) or "FALSE"
            parts = []
            for f in fields:
                terms = []
                for ports, r, join in mine:
                    gate = "" if r is None else f"f_{_ident(r.id)} /\\ "
                    for p in ports:
                        if f not in c.passes.get(p, []):
                            continue
                        sk = sunk(p, f)
                        cond = f"{gate}u_{_ident(p)}" + (f" /\\ ~({sk})" if sk else "")
                        terms.append(f'IF {cond} THEN i_{_ident(p)}.b["{f}"] ELSE 0')
                for r in emitting:
                    if f in r.then[qp]:
                        op, k = r.then[qp][f]
                        R = _ident(r.id)
                        val = {"const": str(k), "keep": f"v_{R}", "max": f"v_{R}", "plus": f"Sat(v_{R} + {k})"}[op]
                        terms.append(f"IF f_{R} THEN {val} ELSE 0")
                terms = list(dict.fromkeys(terms))
                if len(terms) == 1:
                    parts.append((f, f"({terms[0]})"))
                elif terms:
                    parts.append((f, "MaxSet({" + ", ".join(terms) + "})"))
            outs[qp] = (f"[u |-> {sent_x}, n |-> {norm_x}, k |-> [b |-> {_bexpr(parts)}, "
                        f"c |-> all.c, a |-> {auth_out}, t |-> {taint_out}]]")
    fired = " \\cup ".join(f'(IF {x} THEN {{"{rid}"}} ELSE {{}})' for rid, x in fired_terms) or "{}"
    rec = ",\n         ".join(f"{_ident(qp)} |-> {v}" for qp, v in outs.items())
    L.append(f"\\* {c.kind} {c.id}" + (f" (guard on {c.on_edge}{', on a cycle' if c.on_cycle else ''}"
                                        f"{f', acts from phase {stratum}' if stratum else ''})" if c.is_guard else ""))
    L.append(f"Outs_{cid}(lab, F, ph) ==")
    L.append("  LET " + "\n      ".join(lets))
    L.append(f"  IN [{rec},\n         fired |-> {fired}]")
    L.append("")
